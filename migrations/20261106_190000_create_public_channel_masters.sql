-- チャネル名簿 PR-A: 全社1つのチャネル名簿 public.channel_masters と、会社ごとの「隠す」設定の表を作る（作るだけ・冪等）
--
-- 設計: docs/handoff/channel-master-shared/design.md §2・§2-2・§6 の1
-- public.channel_masters: tenant_id が NULL の行は共用（運営が管理）、値が入る行は会社が足した行（手入力 manual のみ）。
-- public.channel_master_tenant_settings: 会社ごとの「隠す」だけを1行で持つ。行が無い＝隠していない。
-- RLS: ADR-145 の4つの守りを写す（migrations/20260626_130000_force_rls_public_products.sql）。ENABLE と FORCE の両方。
-- 行を入れる文は書かない（共用6行は別のデータ変更で PO が流す・ADR-1007）。この便では作るだけで、どこからも読まれない。
--
-- ロールバック: 表は残してプログラムが使わない（表を消すのは別便・PO GO）。

BEGIN;

CREATE TABLE IF NOT EXISTS public.channel_masters (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          INTEGER NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    platform           VARCHAR(50) NOT NULL,
    display_name       VARCHAR(100) NOT NULL,
    connection_type    VARCHAR(10) NOT NULL CHECK (connection_type IN ('auto','manual')),
    conversation_store VARCHAR(20) NOT NULL CHECK (conversation_store IN ('meta_messages','conversation_logs')),
    is_verbatim        BOOLEAN NOT NULL DEFAULT TRUE,
    conversion_item    VARCHAR(30) NULL CHECK (conversion_item IN ('baseline','channel_whatsapp','channel_instagram')),
    is_active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT channel_masters_item_shared_only CHECK (tenant_id IS NULL OR conversion_item IS NULL),
    CONSTRAINT channel_masters_tenant_manual_only CHECK (tenant_id IS NULL OR connection_type = 'manual')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_channel_masters_shared_platform ON public.channel_masters (platform) WHERE tenant_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_channel_masters_tenant_platform ON public.channel_masters (tenant_id, platform) WHERE tenant_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_channel_masters_conversion_item ON public.channel_masters (conversion_item) WHERE conversion_item IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_channel_masters_tenant_id ON public.channel_masters (tenant_id);

COMMENT ON TABLE public.channel_masters IS '全社1つのチャネル名簿。tenant_id が NULL の行は共用（運営が管理）、値が入る行は会社が足した手入力の行';
COMMENT ON COLUMN public.channel_masters.id IS '名簿の行の番号';
COMMENT ON COLUMN public.channel_masters.tenant_id IS '会社 tenants.id。NULL＝共用（運営が管理）';
COMMENT ON COLUMN public.channel_masters.platform IS 'leads.channel_type 等に入る値（チャネルの記号）';
COMMENT ON COLUMN public.channel_masters.display_name IS '画面に出すチャネルの名前';
COMMENT ON COLUMN public.channel_masters.connection_type IS '取り込み方。auto＝連携の部品が自動で取り込む／manual＝手入力。会社が足す行は manual だけ';
COMMENT ON COLUMN public.channel_masters.conversation_store IS '会話の置き場。meta_messages＝Meta の会話／conversation_logs＝手入力の会話ログ';
COMMENT ON COLUMN public.channel_masters.is_verbatim IS '会話の文がお客さんの原文か（電話・対面は要約なので FALSE）';
COMMENT ON COLUMN public.channel_masters.conversion_item IS '成約の分析の項目（baseline・channel_whatsapp・channel_instagram）。共用行だけに付き、会社の行は NULL';
COMMENT ON COLUMN public.channel_masters.is_active IS '名簿に載せるか。FALSE＝名簿からの取り下げ（「消す」）';
COMMENT ON COLUMN public.channel_masters.created_at IS '作った時刻';
COMMENT ON COLUMN public.channel_masters.updated_at IS '直した時刻';

ALTER TABLE public.channel_masters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.channel_masters FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS channel_masters_select ON public.channel_masters;
CREATE POLICY channel_masters_select ON public.channel_masters FOR SELECT
  USING (
    tenant_id IS NULL
    OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER
  );

DROP POLICY IF EXISTS channel_masters_insert ON public.channel_masters;
CREATE POLICY channel_masters_insert ON public.channel_masters FOR INSERT
  WITH CHECK (
    CASE WHEN tenant_id IS NULL THEN current_setting('app.is_operator', true) = 'true'
         ELSE tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER END
  );

DROP POLICY IF EXISTS channel_masters_update ON public.channel_masters;
CREATE POLICY channel_masters_update ON public.channel_masters FOR UPDATE
  USING (
    CASE WHEN tenant_id IS NULL THEN current_setting('app.is_operator', true) = 'true'
         ELSE tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER END
  )
  WITH CHECK (
    CASE WHEN tenant_id IS NULL THEN current_setting('app.is_operator', true) = 'true'
         ELSE tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER END
  );

DROP POLICY IF EXISTS channel_masters_delete ON public.channel_masters;
CREATE POLICY channel_masters_delete ON public.channel_masters FOR DELETE
  USING (
    CASE WHEN tenant_id IS NULL THEN current_setting('app.is_operator', true) = 'true'
         ELSE tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER END
  );

CREATE TABLE IF NOT EXISTS public.channel_master_tenant_settings (
    tenant_id          INTEGER NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    channel_master_id  INTEGER NOT NULL REFERENCES public.channel_masters(id) ON DELETE CASCADE,
    is_hidden          BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by_user_id INTEGER NULL,
    PRIMARY KEY (tenant_id, channel_master_id)
);

COMMENT ON TABLE public.channel_master_tenant_settings IS '会社ごとの「隠す」設定。名簿の行は写さず、隠す行だけを1行で持つ。行が無い＝隠していない';
COMMENT ON COLUMN public.channel_master_tenant_settings.tenant_id IS '会社 tenants.id';
COMMENT ON COLUMN public.channel_master_tenant_settings.channel_master_id IS '名簿の行 channel_masters.id（手入力 manual の行だけ指せる）';
COMMENT ON COLUMN public.channel_master_tenant_settings.is_hidden IS 'この会社で隠すか。TRUE＝隠す（戻せる切り替え）';
COMMENT ON COLUMN public.channel_master_tenant_settings.updated_at IS '直した時刻';
COMMENT ON COLUMN public.channel_master_tenant_settings.updated_by_user_id IS '直した人 users.id（外部キーなし）';

ALTER TABLE public.channel_master_tenant_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.channel_master_tenant_settings FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS channel_master_tenant_settings_select ON public.channel_master_tenant_settings;
CREATE POLICY channel_master_tenant_settings_select ON public.channel_master_tenant_settings FOR SELECT
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER);

DROP POLICY IF EXISTS channel_master_tenant_settings_insert ON public.channel_master_tenant_settings;
CREATE POLICY channel_master_tenant_settings_insert ON public.channel_master_tenant_settings FOR INSERT
  WITH CHECK (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER
    AND EXISTS (
      SELECT 1 FROM public.channel_masters cm
      WHERE cm.id = channel_master_id
        AND cm.connection_type = 'manual'
        AND (cm.tenant_id IS NULL OR cm.tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER)
    )
  );

DROP POLICY IF EXISTS channel_master_tenant_settings_update ON public.channel_master_tenant_settings;
CREATE POLICY channel_master_tenant_settings_update ON public.channel_master_tenant_settings FOR UPDATE
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER)
  WITH CHECK (
    tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER
    AND EXISTS (
      SELECT 1 FROM public.channel_masters cm
      WHERE cm.id = channel_master_id
        AND cm.connection_type = 'manual'
        AND (cm.tenant_id IS NULL OR cm.tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER)
    )
  );

DROP POLICY IF EXISTS channel_master_tenant_settings_delete ON public.channel_master_tenant_settings;
CREATE POLICY channel_master_tenant_settings_delete ON public.channel_master_tenant_settings FOR DELETE
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::INTEGER);

DO $$
DECLARE
    seq text;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'salesanchor_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE
            ON public.channel_masters, public.channel_master_tenant_settings TO salesanchor_app;
        seq := pg_get_serial_sequence('public.channel_masters', 'id');
        IF seq IS NOT NULL THEN
            EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO salesanchor_app', seq);
        END IF;
    END IF;
END $$;

COMMIT;
