-- ============================================================================
-- Step 1: public.units
-- 単位マスタ（例: 枚, 冊, 個, BOX 等）
-- 現: tenant_004.units (8 rows, UUID PK)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.units (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR NOT NULL,
    canonical   TEXT NOT NULL,
    kubun       VARCHAR,
    is_active   BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_units_code ON public.units (code);
CREATE INDEX IF NOT EXISTS idx_units_is_active ON public.units (is_active);

-- ============================================================================
-- Step 2: public.unit_aliases
-- 単位別名マスタ（例: 枚→sheet / 冊→volume 等の多言語対応）
-- 現: tenant_004.unit_aliases (39 rows, UUID PK, UUID FK→units)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.unit_aliases (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id     INTEGER NOT NULL REFERENCES public.units (id),
    alias_text  TEXT NOT NULL,
    lang        VARCHAR NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_unit_aliases_unit_id ON public.unit_aliases (unit_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_unit_aliases_unit_lang ON public.unit_aliases (unit_id, lang, alias_text);

-- ============================================================================
-- Step 3: public.conditions
-- 状態マスタ（例: 新品, 美品, 中古 等）
-- 現: tenant_004.conditions (11 rows, UUID PK)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.conditions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR NOT NULL,
    canonical   TEXT NOT NULL,
    app_kubun   VARCHAR,
    is_active   BOOLEAN NOT NULL DEFAULT true,
    priority    INTEGER,
    search_kw   TEXT NOT NULL DEFAULT '',
    exclude_kw  TEXT NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_conditions_code ON public.conditions (code);
CREATE INDEX IF NOT EXISTS idx_conditions_is_active ON public.conditions (is_active);
CREATE INDEX IF NOT EXISTS idx_conditions_priority ON public.conditions (priority);

-- ============================================================================
-- Step 4: public.condition_aliases
-- 状態別名マスタ（例: 新品→new / 中古→used 等の多言語対応）
-- 現: tenant_004.condition_aliases (31 rows, UUID PK, UUID FK→conditions)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.condition_aliases (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_id  INTEGER NOT NULL REFERENCES public.conditions (id),
    alias_text    TEXT NOT NULL,
    lang          VARCHAR NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_condition_aliases_condition_id ON public.condition_aliases (condition_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_condition_aliases_cond_lang ON public.condition_aliases (condition_id, lang, alias_text);

-- ============================================================================
-- Step 5: public.tcg_note_master
