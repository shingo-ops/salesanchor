--   全テナントが共用できる単一の真実の源（SSOT）を確立する。
--   仕入元マスタ（public.suppliers）と同方式の設計を踏襲。
--
-- 変更内容（DDLのみ — 値操作は SSH 手動実行で別途実施）:
--   Step 1-4 として以下 9 テーブルを public スキーマに新設:
--     1. public.units              （現: tenant_004.units）
--     2. public.unit_aliases       （現: tenant_004.unit_aliases）
--     3. public.conditions         （現: tenant_004.conditions）
--     4. public.condition_aliases  （現: tenant_004.condition_aliases）
--     5. public.tcg_note_master    （現: tenant_004.tcg_note_master）
--     6. public.tcg_status_master  （現: tenant_004.tcg_status_master）
--     7. public.tcg_product_categories（現: tenant_004.tcg_product_categories）
--     8. public.product_search_keywords （現: tenant_004.product_search_keywords）
--     9. public.product_exclude_keywords（現: tenant_004.product_exclude_keywords）
--
-- 設計判断:
--   - UUID id → INTEGER GENERATED BY DEFAULT AS IDENTITY に統一
--   - text id / status_id → INTEGER GENERATED BY DEFAULT AS IDENTITY
--   - updated_at TIMESTAMPTZ NOT NULL DEFAULT now() を全テーブルに追加（supplier SSOT 踏襲）
--   - FK: unit_aliases→units, condition_aliases→conditions,
--         product_*_keywords→products は本 migration で設定
--   - FK: tcg_type_master は Phase 2 で追加（現時点では未設計）
--   - product_id（search/exclude keywords）は INTEGER のまま維持（既に public.products.id 参照）
--
-- 事後実行（SSH手動・PO許可・本 migration 適用後）:
--   - tenant_004 テーブルから public テーブルへデータコピー（ID マッピング含む）
--   - アプリの参照先を tenant_004.* → public.* に切り替え
--   - tenant_004 旧テーブルの DROP（Phase 2 以降・PO確認後）
--
-- 冪等性:
--   - CREATE TABLE IF NOT EXISTS で全テーブル作成
--   - CREATE INDEX IF NOT EXISTS で全インデックス作成
--
-- 注意（ADR-155 migration-guard 制約）:
--   - INSERT/UPDATE/DELETE on 保護テーブルは禁止（Check 7）→ DDL のみ
--   - SELECT on 保護テーブルは禁止（Check 8）→ 存在確認不要（IF NOT EXISTS 使用）
--   - DROP TABLE は本 migration では実施しない（Phase 2 以降・別 migration）
--
-- 作成日: 2026-09-19
