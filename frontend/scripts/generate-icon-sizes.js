import postcss from 'postcss';
import { readFile, open, rename, unlink, realpath } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const KEYS = Object.freeze(['sm', 'md', 'base', 'lg', 'xl']);
const NAMES = new Map(KEYS.map((key) => [`--icon-${key}`, key]));
const PX = /^([+-]?(?:\d*\.\d+|\d+)(?:[eE][+-]?\d+)?)px$/;

function failure(message, exitCode, cause) {
  return Object.assign(new Error(message, { cause }), { exitCode });
}

/** Parse the CSS source; validation errors are 1, CSS syntax errors are 2. */
export function parseIconSizes(css) {
  let root;
  try {
    root = postcss.parse(css);
  } catch (cause) {
    throw failure('Cannot parse icon token CSS', 2, cause);
  }
  const values = {};
  root.walkDecls((decl) => {
    const key = NAMES.get(decl.prop);
    if (!key) return;
    const parent = decl.parent;
    if (parent.type !== 'rule' || parent.parent !== root || parent.selector.trim() !== ':root') {
      throw failure(`${decl.prop} must belong to a top-level standalone :root`, 1);
    }
    if (Object.hasOwn(values, key)) throw failure(`Duplicate ${decl.prop}`, 1);
    if (decl.important) throw failure(`Important declaration is forbidden: ${decl.prop}`, 1);
    const match = PX.exec(decl.value.trim());
    const value = match ? Number(match[1]) : NaN;
    if (!Number.isFinite(value) || value <= 0) {
      throw failure(`${decl.prop} must be a finite positive px number`, 1);
    }
    values[key] = value;
  });
  for (const key of KEYS) {
    if (!Object.hasOwn(values, key)) throw failure(`Missing --icon-${key}`, 1);
  }
  return Object.fromEntries(KEYS.map((key) => [key, values[key]]));
}

/** Emit stable key order and an explicit generated-file notice. */
export function renderIconSizes(values) {
  for (const key of KEYS) {
    if (typeof values[key] !== 'number' || !Number.isFinite(values[key]) || values[key] <= 0) {
      throw failure(`Invalid rendered icon size: ${key}`, 1);
    }
  }
  return [
    '/**',
    ' * Generated from src/tokens.css by scripts/generate-icon-sizes.js.',
    ' * Do not edit this file. Run npm run generate:icon-sizes after editing the CSS source.',
    ' */',
    'export const ICON = {',
    ...KEYS.map((key) => `  ${key}: ${values[key]},`),
    '} as const;',
    '',
    'export type IconSize = (typeof ICON)[keyof typeof ICON];',
    '',
  ].join('\n');
}

/** Return 0 on success; throw an error carrying exitCode 1 or 2 on failure. */
export async function generateIconSizes({ sourcePath, targetPath, check = false }) {
  let css;
  try {
    css = await readFile(sourcePath, 'utf8');
  } catch (cause) {
    throw failure('Cannot read icon token CSS', 2, cause);
  }
  const output = renderIconSizes(parseIconSizes(css));
  let current;
  try {
    current = await readFile(targetPath, 'utf8');
  } catch (cause) {
    if (cause.code !== 'ENOENT') throw failure('Cannot read generated icon sizes', 2, cause);
  }
  if (current === output) return 0;
  if (check) throw failure('Generated icon sizes do not match the CSS source', 1);

  const temporary = join(dirname(targetPath), `.${Date.now()}-${process.pid}-${Math.random().toString(16).slice(2)}-icon-sizes.tmp`);
  let handle;
  let created = false;
  try {
    handle = await open(temporary, 'wx');
    created = true;
    await handle.writeFile(output, 'utf8');
    await handle.close();
    handle = undefined;
    await rename(temporary, targetPath);
    created = false;
    return 0;
  } catch (cause) {
    throw failure('Cannot write generated icon sizes', 2, cause);
  } finally {
    if (handle) await handle.close().catch(() => {});
    if (created) await unlink(temporary).catch(() => {});
  }
}

async function main(args) {
  if (args.length > 1 || args.some((arg) => arg !== '--check')) {
    throw failure('Usage: node scripts/generate-icon-sizes.js [--check]', 1);
  }
  const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  return generateIconSizes({
    sourcePath: join(frontend, 'src/tokens.css'),
    targetPath: join(frontend, 'src/constants/iconSizes.ts'),
    check: args.length === 1,
  });
}

const entryPath = process.argv[1] ? await realpath(resolve(process.argv[1])).catch(() => undefined) : undefined;
if (entryPath && import.meta.url === pathToFileURL(entryPath).href) {
  main(process.argv.slice(2)).then(
    (code) => { process.exitCode = code; },
    (error) => {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = error.exitCode === 1 ? 1 : 2;
    },
  );
}
