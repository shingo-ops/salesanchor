import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, stat, readdir, mkdir, rm, utimes, chmod } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { copyFile, symlink } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseIconSizes, renderIconSizes, generateIconSizes } from './generate-icon-sizes.js';

const VALUES = { sm: 14, md: 16, base: 20, lg: 24, xl: 48 };
const CSS = `:root { ${Object.entries(VALUES).map(([key, value]) => `--icon-${key}: ${value}px;`).join(' ')} }`;
const errorCode = (code) => (error) => error.exitCode === code;

async function fixture(t) {
  const directory = await mkdtemp(join(tmpdir(), 'icon-source-test-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const sourcePath = join(directory, 'tokens.css');
  const targetPath = join(directory, 'iconSizes.ts');
  await writeFile(sourcePath, CSS);
  return { directory, sourcePath, targetPath };
}

async function snapshot(path) {
  const metadata = await stat(path);
  return { text: await readFile(path, 'utf8'), inode: metadata.ino, modified: metadata.mtimeMs };
}

test('current five CSS values preserve the numeric ICON API', () => {
  assert.deepEqual(parseIconSizes(CSS), VALUES);
  const rendered = renderIconSizes(VALUES);
  for (const [key, value] of Object.entries(VALUES)) assert.ok(rendered.includes(`  ${key}: ${value},`));
  assert.ok(rendered.includes('export type IconSize = (typeof ICON)[keyof typeof ICON];'));
  assert.ok(rendered.includes('Generated from src/tokens.css'));
});

test('declaration and input object order do not change generated bytes', () => {
  const reverse = Object.fromEntries(Object.entries(VALUES).reverse());
  const css = `:root { ${Object.entries(reverse).map(([k, v]) => `--icon-${k}:${v}px;`).join('')} }`;
  assert.equal(renderIconSizes(parseIconSizes(css)), renderIconSizes(VALUES));
  assert.equal(renderIconSizes(reverse), renderIconSizes(VALUES));
});

test('one changed CSS value changes only its generated value', () => {
  assert.equal(renderIconSizes(parseIconSizes(CSS.replace('14px', '15px'))),
    renderIconSizes(VALUES).replace('sm: 14,', 'sm: 15,'));
});

test('missing and duplicate declarations fail validation', () => {
  assert.throws(() => parseIconSizes(CSS.replace('--icon-sm: 14px;', '')), errorCode(1));
  assert.throws(() => parseIconSizes(`${CSS} :root { --icon-sm:14px; }`), errorCode(1));
});

for (const selector of ['.other', ':root, .other', ':root.force-dark']) {
  test(`target declaration under ${selector} is rejected`, () => {
    assert.throws(() => parseIconSizes(`${CSS} ${selector} { --icon-sm:14px; }`), errorCode(1));
  });
}

test('conditional and nested target declarations are rejected', () => {
  for (const extra of ['@media (max-width:1px){:root{--icon-sm:14px;}}',
    ':root { .child { --icon-sm:14px; } }', '@supports(display:grid){:root{--icon-sm:14px;}}']) {
    assert.throws(() => parseIconSizes(CSS + extra), errorCode(1));
  }
});

for (const value of ['1rem', 'var(--space-4)', 'calc(7px * 2)', '0px', '-1px', '1e309px', '1e-400px', 'NaNpx', '14px !important']) {
  test(`invalid size ${value} is rejected`, () => {
    assert.throws(() => parseIconSizes(CSS.replace('14px', value)), errorCode(1));
  });
}

test('finite fractional px is valid and unrelated tokens are ignored', () => {
  assert.equal(parseIconSizes(CSS.replace('14px', '.5px')).sm, 0.5);
  assert.deepEqual(parseIconSizes(CSS + '@media print {:root {--unrelated:var(--x);}}'), VALUES);
});

test('malformed CSS is an operational parse error', () => {
  assert.throws(() => parseIconSizes(':root { --icon-sm: 14px;'), errorCode(2));
});

test('atomic generation replaces output, leaving no temporary file', async (t) => {
  const f = await fixture(t);
  await writeFile(f.targetPath, 'previous output');
  assert.equal(await generateIconSizes(f), 0);
  assert.equal(await readFile(f.targetPath, 'utf8'), renderIconSizes(VALUES));
  assert.deepEqual((await readdir(f.directory)).sort(), ['iconSizes.ts', 'tokens.css']);
});

test('equal output and matching check preserve bytes, inode and timestamp', async (t) => {
  const f = await fixture(t);
  await generateIconSizes(f);
  await utimes(f.targetPath, 946684800, 946684800);
  const before = await snapshot(f.targetPath);
  assert.equal(await generateIconSizes(f), 0);
  assert.equal(await generateIconSizes({ ...f, check: true }), 0);
  assert.deepEqual(await snapshot(f.targetPath), before);
  assert.deepEqual((await readdir(f.directory)).sort(), ['iconSizes.ts', 'tokens.css']);
});

test('mismatched check does not change the previous output', async (t) => {
  const f = await fixture(t);
  await writeFile(f.targetPath, 'previous output');
  const before = await snapshot(f.targetPath);
  await assert.rejects(generateIconSizes({ ...f, check: true }), errorCode(1));
  assert.deepEqual(await snapshot(f.targetPath), before);
  assert.deepEqual((await readdir(f.directory)).sort(), ['iconSizes.ts', 'tokens.css']);
});

test('missing check output remains absent', async (t) => {
  const f = await fixture(t);
  await assert.rejects(generateIconSizes({ ...f, check: true }), errorCode(1));
  assert.deepEqual(await readdir(f.directory), ['tokens.css']);
});

test('invalid input or parse failure preserves the previous output', async (t) => {
  const f = await fixture(t);
  await writeFile(f.targetPath, 'previous output');
  const before = await snapshot(f.targetPath);
  for (const [css, code] of [[CSS.replace('14px', '0px'), 1], [':root {', 2]]) {
    await writeFile(f.sourcePath, css);
    await assert.rejects(generateIconSizes(f), errorCode(code));
    assert.deepEqual(await snapshot(f.targetPath), before);
  }
});

test('missing source and unavailable output directory are operational errors', async (t) => {
  const f = await fixture(t);
  await assert.rejects(generateIconSizes({ ...f, sourcePath: join(f.directory, 'missing') }), errorCode(2));
  await assert.rejects(generateIconSizes({ ...f, targetPath: join(f.directory, 'missing', 'out.ts') }), errorCode(2));
  assert.deepEqual(await readdir(f.directory), ['tokens.css']);
});

test('output read failure is operational and does not replace a directory', async (t) => {
  const f = await fixture(t);
  await mkdir(f.targetPath);
  await assert.rejects(generateIconSizes(f), errorCode(2));
  assert.equal((await stat(f.targetPath)).isDirectory(), true);
});

test('failed atomic write retains existing output', {
  skip: process.platform === 'win32' || process.getuid?.() === 0,
}, async (t) => {
  const f = await fixture(t);
  await writeFile(f.targetPath, 'previous output');
  const before = await snapshot(f.targetPath);
  await chmod(f.directory, 0o555);
  try {
    await assert.rejects(generateIconSizes(f), errorCode(2));
    assert.deepEqual(await snapshot(f.targetPath), before);
  } finally {
    await chmod(f.directory, 0o755);
  }
});


async function cliFixture(t) {
  const directory = await mkdtemp(join(tmpdir(), 'icon-cli-test-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await mkdir(join(directory, 'scripts'));
  await mkdir(join(directory, 'src', 'constants'), { recursive: true });
  await mkdir(join(directory, 'node_modules'));
  await writeFile(join(directory, 'package.json'), '{"type":"module"}');
  const script = join(directory, 'scripts', 'generate-icon-sizes.js');
  await copyFile(fileURLToPath(new URL('./generate-icon-sizes.js', import.meta.url)), script);
  const require = createRequire(import.meta.url);
  await symlink(dirname(require.resolve('postcss/package.json')), join(directory, 'node_modules', 'postcss'), 'dir');
  const sourcePath = join(directory, 'src', 'tokens.css');
  const targetPath = join(directory, 'src', 'constants', 'iconSizes.ts');
  await writeFile(sourcePath, CSS);
  return { directory, script, sourcePath, targetPath };
}

function child(args, cwd) {
  const result = spawnSync(process.execPath, args, { cwd, encoding: 'utf8' });
  assert.ifError(result.error);
  assert.equal(result.signal, null, result.stderr);
  return result;
}

test('CLI generates the five values with exit 0', async (t) => {
  const f = await cliFixture(t);
  const result = child([f.script], f.directory);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(await readFile(f.targetPath, 'utf8'), renderIconSizes(VALUES));
});

test('CLI matching --check preserves output with exit 0', async (t) => {
  const f = await cliFixture(t);
  await writeFile(f.targetPath, renderIconSizes(VALUES));
  const before = await snapshot(f.targetPath);
  const result = child([f.script, '--check'], f.directory);
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(await snapshot(f.targetPath), before);
});

test('CLI mismatched --check preserves output with exit 1', async (t) => {
  const f = await cliFixture(t);
  await writeFile(f.targetPath, 'previous output');
  const before = await snapshot(f.targetPath);
  assert.equal(child([f.script, '--check'], f.directory).status, 1);
  assert.deepEqual(await snapshot(f.targetPath), before);
});

for (const args of [['--unknown'], ['--check', '--check']]) {
  test(`CLI rejects ${args.join(' ')} with exit 1 and preserves output`, async (t) => {
    const f = await cliFixture(t);
    await writeFile(f.targetPath, 'previous output');
    const before = await snapshot(f.targetPath);
    assert.equal(child([f.script, ...args], f.directory).status, 1);
    assert.deepEqual(await snapshot(f.targetPath), before);
  });
}

test('CLI uses its source directory when invoked from a different CWD', async (t) => {
  const f = await cliFixture(t);
  const cwd = join(f.directory, 'unrelated');
  await mkdir(cwd);
  const result = child([f.script], cwd);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(await readFile(f.targetPath, 'utf8'), renderIconSizes(VALUES));
  assert.deepEqual(await readdir(cwd), []);
});

for (const operation of ['writeFile', 'rename']) {
  test(`CLI ${operation} failure exits 2, preserves old output and removes temporary file`, async (t) => {
    const f = await cliFixture(t);
    await writeFile(f.targetPath, 'previous output');
    const before = await snapshot(f.targetPath);
    const program = `
      import fs from 'node:fs/promises';
      import { mock } from 'node:test';
      import { syncBuiltinESMExports } from 'node:module';
      const failure = () => Object.assign(new Error('injected ${operation} failure'), { code: 'EIO' });
      if (${JSON.stringify(operation)} === 'writeFile') {
        const originalOpen = fs.open;
        mock.method(fs, 'open', async (...args) => {
          const handle = await originalOpen(...args);
          return {
            writeFile: async (text) => {
              await handle.writeFile(text.slice(0, 7), 'utf8');
              throw failure();
            },
            close: () => handle.close(),
          };
        });
      } else {
        mock.method(fs, 'rename', async () => { throw failure(); });
      }
      syncBuiltinESMExports();
      process.argv = [process.execPath, ${JSON.stringify(f.script)}];
      await import(${JSON.stringify(pathToFileURL(f.script).href)});
    `;
    const result = child(['--input-type=module', '--eval', program], f.directory);
    assert.equal(result.status, 2, result.stderr);
    assert.match(result.stderr, /Cannot write generated icon sizes/);
    assert.deepEqual(await snapshot(f.targetPath), before);
    assert.deepEqual(await readdir(dirname(f.targetPath)), ['iconSizes.ts']);
  });
}
