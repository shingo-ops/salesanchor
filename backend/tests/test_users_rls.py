# ③ 文脈なしでは書けない（UPDATE・DELETE は 0 行、INSERT は 42501）
async def test_no_context_cannot_write():
    from sqlalchemy import text
    from sqlalchemy.exc import DBAPIError

    async with _fresh() as (admin_engine, app_engine):
        for target in (_USER_A, _USER_B):
            conn, trans = await _ctx_conn(app_engine, None)
            try:
                r = await conn.execute(
                    text("UPDATE public.users SET username = 'x' WHERE id = :u"), {"u": target}
                )
                assert r.rowcount == 0, target
                r = await conn.execute(text("DELETE FROM public.users WHERE id = :u"), {"u": target})
                assert r.rowcount == 0, target
            finally:
                await trans.rollback()
                await conn.close()
        conn, trans = await _ctx_conn(app_engine, None)
        try:
            with pytest.raises(DBAPIError) as exc_info:
                await conn.execute(
                    text(_INSERT_USER), {"i": 9001, "t": _TENANT_A, "n": "n", "e": "n@example.com"}
                )
            assert _sqlstate(exc_info.value) == "42501"
        finally:
            await trans.rollback()
            await conn.close()
        rows = await _admin_exec(
            admin_engine, "SELECT id, username FROM public.users WHERE id IN (:a, :b) ORDER BY id",
            {"a": _USER_A, "b": _USER_B},
        )
        assert rows == [(_USER_A, f"u{_USER_A}"), (_USER_B, f"u{_USER_B}")]


