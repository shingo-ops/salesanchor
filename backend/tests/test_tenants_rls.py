# ③ 会社文脈・文脈なしでは自社も他社も書けない
async def test_tenant_context_and_no_context_cannot_write():
    from sqlalchemy import text
    from sqlalchemy.exc import DBAPIError

    async with _fresh() as (admin_engine, app_engine):
        for ctx in (_TENANT_A, None):
            for target in (_TENANT_A, _TENANT_B):
                conn, trans = await _ctx_conn(app_engine, ctx)
                try:
                    r = await conn.execute(
                        text("UPDATE public.tenants SET tenant_name = 'x' WHERE id = :t"), {"t": target}
                    )
                    assert r.rowcount == 0, (ctx, target)
                    r = await conn.execute(text("DELETE FROM public.tenants WHERE id = :t"), {"t": target})
                    assert r.rowcount == 0, (ctx, target)
                finally:
                    await trans.rollback()
                    await conn.close()
            conn, trans = await _ctx_conn(app_engine, ctx)
            try:
                with pytest.raises(DBAPIError) as exc_info:
                    await conn.execute(text(_INSERT_TENANT), {"i": 9000, "c": "tenant_9000"})
                assert _sqlstate(exc_info.value) == "42501", ctx
            finally:
                await trans.rollback()
                await conn.close()
        rows = await _admin_exec(
            admin_engine, "SELECT id, tenant_name FROM public.tenants WHERE id IN (:a, :b) ORDER BY id",
            {"a": _TENANT_A, "b": _TENANT_B},
        )
        assert rows == [(_TENANT_A, f"tenant_{_TENANT_A}"), (_TENANT_B, f"tenant_{_TENANT_B}")]


