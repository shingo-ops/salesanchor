# ⑤ 運営文脈で会社を削除すると子表が連鎖で消える
async def test_operator_delete_cascades_to_children():
    from sqlalchemy import text

    async with _fresh() as (admin_engine, app_engine):
        await _admin_exec(
            admin_engine,
            "INSERT INTO public.tenant_paypal_config "
            "(tenant_id, client_id_encrypted, client_secret_encrypted) VALUES (:t, 'c', 's')",
            {"t": _TENANT_B},
        )
        await _admin_exec(
            admin_engine,
            "INSERT INTO public.registration_tokens "
            "(tenant_id, lead_id, token_hash, type, expires_at, created_by) "
            "VALUES (:t, 1, :h, 'register', NOW() + INTERVAL '7 days', 999)",
            {"t": _TENANT_B, "h": uuid.uuid4().hex + uuid.uuid4().hex},
        )
        conn, trans = await _ctx_conn(app_engine, None, operator=True)
        try:
            r = await conn.execute(text("DELETE FROM public.tenants WHERE id = :t"), {"t": _TENANT_B})
            assert r.rowcount == 1
            await trans.commit()
        finally:
            await conn.close()
        for table, col in (
            ("public.users", "tenant_id"),
            ("public.tenant_paypal_config", "tenant_id"),
            ("public.registration_tokens", "tenant_id"),
        ):
            n = (
                await _admin_exec(
                    admin_engine, f"SELECT count(*) FROM {table} WHERE {col} = :t", {"t": _TENANT_B}
                )
            )[0][0]
            assert n == 0, table


