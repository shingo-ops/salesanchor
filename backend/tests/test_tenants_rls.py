# ⑦ 3 ルートの運営文脈を外した複製は効かない（外すと本当に止まることの確認）
async def test_routes_without_operator_context_do_not_write(monkeypatch):
    from sqlalchemy.exc import DBAPIError

    from app.routers import admin as admin_mod
    from app.routers import super_admin_tenants as mod

    async def _noop(*_a, **_k):
        return None

    _noop_cache(monkeypatch, mod)
    monkeypatch.setattr(mod, "set_operator_context", _noop)
    monkeypatch.setattr(admin_mod, "set_operator_context", _noop)
    monkeypatch.setattr(admin_mod, "create_tenant_schema", _noop)
    monkeypatch.setattr(admin_mod, "record_audit_log", _noop)
    async with _fresh() as (admin_engine, app_engine):
        # T1: 会社作成は 42501
        async with _session(app_engine) as db, _session(admin_engine) as admin_db:
            with pytest.raises(DBAPIError) as exc_info:
                await admin_mod.register_tenant(
                    admin_mod.TenantCreate(tenant_name="new-co", tenant_code="new-co"), db, admin_db, _OPERATOR
                )
            assert _sqlstate(exc_info.value) == "42501"
        # T2: 論理削除は無言で 0 行（is_active が変わらない）
        async with _session(app_engine) as db:
            await mod.delete_tenant_logical(
                _TENANT_B, mod.TenantDeleteRequest(confirm=f"DELETE:tenant_{_TENANT_B}"), _OPERATOR, db
            )
        rows = await _admin_exec(admin_engine, "SELECT is_active FROM public.tenants WHERE id = :t", {"t": _TENANT_B})
        assert rows == [(True,)]
        # T3: 物理削除は無言で 0 行（行が残る）
        await _admin_exec(admin_engine, "UPDATE public.tenants SET is_active = FALSE WHERE id = :t", {"t": _TENANT_B})
        async with _session(app_engine) as db, _session(admin_engine) as admin_db:
            await mod.delete_tenant_physical(
                _TENANT_B, mod.TenantDeleteRequest(confirm=f"DELETE:tenant_{_TENANT_B}"), _OPERATOR, db, admin_db
            )
        rows = await _admin_exec(admin_engine, "SELECT id FROM public.tenants WHERE id = :t", {"t": _TENANT_B})
        assert rows == [(_TENANT_B,)]
