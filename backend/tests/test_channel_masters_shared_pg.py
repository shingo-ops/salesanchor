"""public.channel_masters / public.channel_master_tenant_settings の守り（PostgreSQL・RLS）。

使い捨て DB を試験ごとに作り、本物の migration を適用して、アプリ接続役（NOBYPASSRLS）で確かめる。
RLS_ADMIN_DATABASE_URL / RLS_TEST_DATABASE_URL が無ければ skip。会社番号は 976 / 977。
"""
from __future__ import annotations

import os
import uuid
from contextlib import asynccontextmanager
from urllib.parse import urlsplit, urlunsplit

import pytest

from tests.rls_bootstrap import _apply_migration, _ensure_public_users

ADMIN_PG_URL = os.getenv("RLS_ADMIN_DATABASE_URL") or os.getenv("TEST_PG_URL")
APP_PG_URL = os.getenv("RLS_TEST_DATABASE_URL")

pytestmark = [
    pytest.mark.skipif(
        not ADMIN_PG_URL or not APP_PG_URL,
        reason=(
            "実 PostgreSQL 環境が必要 "
            "(RLS_ADMIN_DATABASE_URL / RLS_TEST_DATABASE_URL 未設定)。"
        ),
    ),
    pytest.mark.asyncio,
]

_TENANT_A = 976
_TENANT_B = 977
_MIGRATION = "20261106_190000_create_public_channel_masters.sql"
_GRANT_DDL = """
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO salesanchor_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO salesanchor_app;
"""
_BOOTSTRAP_EXTRA_DDL = """
ALTER TABLE public.tenants ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW();
ALTER TABLE public.tenants ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();
ALTER TABLE public.tenants ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 5000);
"""


def _with_db(url: str, name: str) -> str:
    return urlunsplit(urlsplit(url)._replace(path="/" + name))


@asynccontextmanager
async def _fresh():
    """使い捨て DB を作り (admin_engine, app_engine, ids) を返す。終了時に DROP。"""
    from sqlalchemy import text
    from sqlalchemy.ext.asyncio import create_async_engine

    control = create_async_engine(ADMIN_PG_URL, isolation_level="AUTOCOMMIT")
    name = "chm_rls_" + uuid.uuid4().hex[:12]
    async with control.connect() as conn:
        await conn.execute(text(f'CREATE DATABASE "{name}"'))
    admin_engine = create_async_engine(_with_db(ADMIN_PG_URL, name), echo=False)
    app_engine = create_async_engine(_with_db(APP_PG_URL, name), echo=False, pool_size=1, max_overflow=0)
    try:
        async with admin_engine.begin() as conn:
            await _ensure_public_users(conn)
            raw = await conn.get_raw_connection()
            await raw.driver_connection.execute(_BOOTSTRAP_EXTRA_DDL)
            for tid in (_TENANT_A, _TENANT_B):
                await conn.execute(
                    text(
                        "INSERT INTO public.tenants (id, tenant_code, tenant_name, company_name) "
                        "VALUES (:i, :c, :c, :c)"
                    ),
                    {"i": tid, "c": f"tenant_{tid}"},
                )
        await _apply_migration(admin_engine, _MIGRATION)
        async with admin_engine.begin() as conn:
            raw = await conn.get_raw_connection()
            await raw.driver_connection.execute(_GRANT_DDL)
            # 共用の手入力の行（電話）と、B 社が足した行（管理者の役は RLS を通らない）
            shared_id = (
                await conn.execute(
                    text(
                        "INSERT INTO public.channel_masters "
                        "(tenant_id, platform, display_name, connection_type, conversation_store, is_verbatim) "
                        "VALUES (NULL, 'phone', '電話', 'manual', 'conversation_logs', FALSE) RETURNING id"
                    )
                )
            ).scalar_one()
            b_row_id = (
                await conn.execute(
                    text(
                        "INSERT INTO public.channel_masters "
                        "(tenant_id, platform, display_name, connection_type, conversation_store) "
                        "VALUES (:t, 'b_only', 'B only', 'manual', 'conversation_logs') RETURNING id"
                    ),
                    {"t": _TENANT_B},
                )
            ).scalar_one()
        yield admin_engine, app_engine, {"shared": shared_id, "b_row": b_row_id}
    finally:
        await app_engine.dispose()
        await admin_engine.dispose()
        async with control.connect() as conn:
            await conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        await control.dispose()


async def _ctx_conn(app_engine, tenant_id: int):
    from sqlalchemy import text

    conn = await app_engine.connect()
    trans = await conn.begin()
    await conn.execute(text("SELECT set_config('app.tenant_id', :t, true)"), {"t": str(tenant_id)})
    return conn, trans


async def test_tenant_role_cannot_update_shared_row_and_cannot_see_other_tenant_row():
    from sqlalchemy import text

    async with _fresh() as (_admin, app_engine, ids):
        conn, trans = await _ctx_conn(app_engine, _TENANT_A)
        try:
            r = await conn.execute(
                text("UPDATE public.channel_masters SET display_name = 'x' WHERE id = :i"), {"i": ids["shared"]}
            )
            assert r.rowcount == 0
            seen = (
                await conn.execute(text("SELECT count(*) FROM public.channel_masters WHERE id = :i"), {"i": ids["b_row"]})
            ).scalar_one()
            assert seen == 0
            shared_seen = (
                await conn.execute(text("SELECT count(*) FROM public.channel_masters WHERE id = :i"), {"i": ids["shared"]})
            ).scalar_one()
            assert shared_seen == 1
        finally:
            await trans.rollback()
            await conn.close()


async def test_settings_pointing_to_other_tenant_row_is_rejected_by_rls():
    from sqlalchemy import text
    from sqlalchemy.exc import DBAPIError

    async with _fresh() as (_admin, app_engine, ids):
        conn, trans = await _ctx_conn(app_engine, _TENANT_A)
        try:
            with pytest.raises(DBAPIError):
                await conn.execute(
                    text(
                        "INSERT INTO public.channel_master_tenant_settings (tenant_id, channel_master_id, is_hidden) "
                        "VALUES (:t, :m, TRUE)"
                    ),
                    {"t": _TENANT_A, "m": ids["b_row"]},
                )
        finally:
            await trans.rollback()
            await conn.close()


async def test_deleting_tenant_removes_its_rows_in_both_tables():
    from sqlalchemy import text

    async with _fresh() as (admin_engine, _app, ids):
        async with admin_engine.begin() as conn:
            own_id = (
                await conn.execute(
                    text(
                        "INSERT INTO public.channel_masters "
                        "(tenant_id, platform, display_name, connection_type, conversation_store) "
                        "VALUES (:t, 'a_only', 'A only', 'manual', 'conversation_logs') RETURNING id"
                    ),
                    {"t": _TENANT_A},
                )
            ).scalar_one()
            await conn.execute(
                text(
                    "INSERT INTO public.channel_master_tenant_settings (tenant_id, channel_master_id, is_hidden) "
                    "VALUES (:t, :m, TRUE)"
                ),
                {"t": _TENANT_A, "m": ids["shared"]},
            )
            await conn.execute(text("DELETE FROM public.tenants WHERE id = :t"), {"t": _TENANT_A})
            rows = (
                await conn.execute(text("SELECT count(*) FROM public.channel_masters WHERE id = :i"), {"i": own_id})
            ).scalar_one()
            settings = (
                await conn.execute(
                    text("SELECT count(*) FROM public.channel_master_tenant_settings WHERE tenant_id = :t"),
                    {"t": _TENANT_A},
                )
            ).scalar_one()
            assert rows == 0
            assert settings == 0
